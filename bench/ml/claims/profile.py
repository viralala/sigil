"""Writes bench/dataset-profile.md: aggregate counts only, any group under 10 suppressed."""
import os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import claims_lib as L

MIN = 10
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))


def s_(n):
    return str(n) if n >= MIN else "<%d" % MIN


def main():
    d = L.load_csv()
    real = L.real_frame(d)
    n, st = len(d), real.group.nunique()
    per = real.groupby("group").size()
    rows = []
    rows.append("# Dataset profile (aggregate counts only)\n")
    rows.append("Source: a private export of the CESAC student-records table (26 Oct 2026). The file is NOT in this repository and no row, name, email, PRN, phone number, faculty name or link from it is reproduced anywhere in the repo. Any group with fewer than %d members is shown as `<%d`. Generated by `bench/ml/claims/profile.py`.\n" % (MIN, MIN))
    rows.append("## Totals\n")
    rows.append("| Measure | Value |\n|---|---|")
    rows.append("| Records | %d |" % n)
    rows.append("| Distinct students (name, PRN and email linked) | %d |" % st)
    rows.append("| Records per student: median / 90th percentile | %d / %d |" % (np.median(per), np.percentile(per, 90)))
    rows.append("| Records with a title | %d (%.1f%%) |" % (d.title.notna().sum(), 100 * d.title.notna().mean()))
    rows.append("")
    rows.append("## Verification state (all records)\n")
    rows.append("| State | Records |\n|---|---|")
    for k, v in d.state.value_counts(dropna=False).items():
        rows.append("| %s | %s |" % (k, s_(v)))
    rows.append("\nThese states are the source system's own labels (not Sigil witnesses); Sigil does not treat it as a W1 issuer signature.\n")
    rows.append("## Kinds (12 source kinds)\n")
    rows.append("| Source kind | Product kind | Records | Students | verified | waiting |\n|---|---|---|---|---|---|")
    small = []
    for k, g in sorted(real.groupby("kind"), key=lambda kv: -len(kv[1])):
        if len(g) < MIN:
            small.append(k); continue
        stc = g.state.value_counts()
        wide = len(g) >= 2 * MIN  # avoid recovering a hidden cell by subtraction in small groups
        rows.append("| %s | %s | %s | %s | %s | %s |" % (k, L.KIND_MAP[k], s_(len(g)), s_(g.group.nunique()),
                                                        s_(stc.get("verified", 0)) if wide else "<%d" % MIN, s_(stc.get("waiting", 0)) if wide else "<%d" % MIN))
    if small:
        rows.append("| %s (each fewer than %d records) | - | <%d | <%d | <%d | <%d |" % (", ".join(small), MIN, MIN, MIN, MIN, MIN))
    rows.append("")
    rows.append("## Product kinds after mapping (what the classifier learns)\n")
    rows.append("| Product kind | Records | Students |\n|---|---|---|")
    for k, g in sorted(real.groupby("label"), key=lambda kv: -len(kv[1])):
        rows.append("| %s | %s | %s |" % (k, s_(len(g)), s_(g.group.nunique())))
    rows.append("\nNo real records exist for `education`, `skill` or `award`; the model learns those from invented text only (see `bench/ml/claims/report.md`).\n")
    rows.append("## Field coverage by product kind (share of records with an organiser/venue value)\n")
    rows.append("| Product kind | Records | With organiser |\n|---|---|---|")
    org = d["journal_or_conference"].notna()
    for k, g in sorted(real.groupby("label"), key=lambda kv: -len(kv[1])):
        if len(g) >= MIN:
            rows.append("| %s | %s | %.0f%% |" % (k, s_(len(g)), 100 * org[g.index].mean()))
    open(os.path.join(ROOT, "bench", "dataset-profile.md"), "w", encoding="utf-8").write("\n".join(rows) + "\n")
    print("written")


if __name__ == "__main__":
    main()
